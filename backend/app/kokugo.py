def pick_ten(kind: str) -> list[tuple[str, str]]:
    bank = KANJI_YOMI if kind == "かんじのよみ" else JUKUGO_YOMI
    if len(bank) <= 10:
        return list(bank)
    return random.sample(list(bank), 10)
