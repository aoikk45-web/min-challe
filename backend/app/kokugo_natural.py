# 熟語の読みで複数正解を許す（正解キーはバンクの reading）
JUKUGO_READING_ALTERNATES: dict[str, set[str]] = {
    "にほん": {"にほん", "にっぽん"},
}


def plain_sentence(sentence: str) -> str:
    return re.sub(r"\*\*([^*]+)\*\*", r"\1", sentence)


def has_broken_highlight(word: str, sentence: str) -> bool:
    for i in range(1, len(word)):
        if f"**{word[:i]}**" in sentence:
            return True
    return False


def is_standalone_kanji_highlight(char: str, sentence: str) -> bool:
    """漢字の中で他の漢字とくっついていない（単独で読める）か。"""
    plain = plain_sentence(sentence)
    idx = plain.find(char)
    if idx < 0:
        return False
    before = plain[idx - 1] if idx > 0 else ""
    after = plain[idx + 1] if idx + 1 < len(plain) else ""
    if before and "\u4e00" <= before <= "\u9fff":
        return False
    if after and "\u4e00" <= after <= "\u9fff":
        return False
    return True


def is_natural_example(target: str, sentence: str) -> bool:
    plain = plain_sentence(sentence)
    if plain.count(target) != 1:
        return False
    if f"**{target}**" not in sentence:
        return False
    if has_broken_highlight(target, sentence):
        return False
    for phrase in AMBIGUOUS_GENERIC_PHRASES:
        if phrase in plain:
            return False
    for phrase in FORBIDDEN_PHRASES:
        if phrase in plain:
            return False
    return True
