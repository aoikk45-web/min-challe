def clean_kana(raw: str) -> str:
    base = re.sub(r"[-.].*$", "", raw)
    base = katakana_to_hiragana(unicodedata.normalize("NFKC", base))
    if not base:
        return ""
    if not all("\u3040" <= c <= "\u309f" or c in "ーっ" for c in base):
        return ""
    return base.replace("ー", "")


def clean_readings(raw_list: list[str]) -> list[str]:
    out: list[str] = []
    for raw in raw_list or []:
        item = clean_kana(raw)
        if item and item not in out:
            out.append(item)
    return out


def split_yomi(word: str, yomi: str, index: int) -> str | None:
    n = len(word)
    if index < 0 or index >= n:
        return None
    if n == 1:
        return yomi
    if len(yomi) % n == 0:
        size = len(yomi) // n
        return yomi[index * size : (index + 1) * size]
    moras: list[str] = []
    i = 0
    while i < len(yomi):
        if i + 1 < len(yomi) and yomi[i + 1] in "ゃゅょぁぃぅぇぉ":
            moras.append(yomi[i : i + 2])
            i += 2
        elif yomi[i] == "っ" and i + 1 < len(yomi):
            moras.append(yomi[i : i + 2])
            i += 2
        else:
            moras.append(yomi[i])
            i += 1
    if len(moras) < n:
        return None
    base, extra = divmod(len(moras), n)
    pos = 0
    for j in range(n):
        take = base + (1 if j < extra else 0)
        if j == index:
            return "".join(moras[pos : pos + take])
        pos += take
    return None


def embed_char(word: str, index: int) -> str:
    return f"{word[:index]}**{word[index]}**{word[index + 1:]}"


