def sentence_for_jukugo(word: str) -> str | None:
    if word in SKIP_JUKUGO:
        return None
    if word in JUKUGO_SENTENCES:
        return JUKUGO_SENTENCES[word]
    for suffix, template in JUKUGO_SUFFIX_TEMPLATES:
        if word.endswith(suffix):
            return template.format(w=word)
    return None


def highlight_char_in_word(sentence: str, word: str, char_index: int) -> str | None:
    plain = re.sub(r"\*\*([^*]+)\*\*", r"\1", sentence)
    start = plain.find(word)
    if start < 0:
        return None
    pos = start + char_index
    if pos < 0 or pos >= len(plain):
        return None
    char = plain[pos]
    return plain[:pos] + f"**{char}**" + plain[pos + 1 :]


def kun_context(char: str, kun_raw: str) -> tuple[str, str] | None:
    if char in KANJI_KUN_SENTENCES:
        return None
    if "." in kun_raw:
        stem, okuri = kun_raw.split(".", 1)
        okuri = okuri.replace("-", "")
    else:
        stem, okuri = kun_raw, ""
    stem_hira = clean_kana(stem)
    if not stem_hira:
        return None
    if okuri == "つ":
        return f"りんごが **{char}**つ あります。", stem_hira
    if okuri == "人":
        return f"家族は **{char}**人 です。", stem_hira
    if okuri in ("く", "ぐ"):
        return f"ここから **{char}**{okuri}。", stem_hira
    if okuri in ("む", "ぶ", "ぬ"):
        return f"みんなで **{char}**{okuri}。", stem_hira
    if okuri == "す":
        if char == "申":
            return f"ここに **{char}**し込みを しました。", stem_hira
        return f"友達と **{char}**{okuri}。", stem_hira
    if okuri == "き":
        return f"音楽を **{char}**{okuri}。", stem_hira
    if okuri == "み":
        return f"本を **{char}**{okuri}。", stem_hira
    if okuri == "て":
        return f"ごはんを **{char}**{okuri}。", stem_hira
    if okuri == "め":
        return f"水を **{char}**{okuri}。", stem_hira
    if okuri.startswith("が"):
        return f"階段を **{char}**がりました。", stem_hira
    if okuri.startswith("り") and okuri != "り":
        return f"階段を **{char}**りました。", stem_hira
    if okuri.startswith("べ"):
        return f"ごはんを **{char}**べます。", stem_hira
    if okuri.startswith("み"):
        return f"テレビを **{char}**みます。", stem_hira
    if okuri.startswith("き"):
        return f"音楽を **{char}**きます。", stem_hira
    if okuri.startswith("よ"):
        return f"本を **{char}**みます。", stem_hira
    if okuri.startswith("か"):
        return f"字を **{char}**きます。", stem_hira
    if okuri.startswith("はな"):
        return f"友達と **{char}**します。", stem_hira
    if okuri.startswith("い"):
        return f"本当のことを **{char}**います。", stem_hira
    if okuri == "ける":
        return f"お花に **{char}**けました。", stem_hira
    return None


def plain_sentence(sentence: str) -> str:
    return re.sub(r"\*\*([^*]+)\*\*", r"\1", sentence)


def distinct_readings(meta: dict) -> set[str]:
    kun = clean_readings(meta.get("readings_kun") or [])
    on = clean_readings(meta.get("readings_on") or [])
    return set(kun + on)


def is_disambiguated_example(char: str, sentence: str, meta: dict) -> bool:
    if not is_natural_example(char, sentence):
        return False
    plain = plain_sentence(sentence)
    curated = (
        any(s == sentence for s, _ in NUMBER_CONTEXT.get(char, []))
        or any(s == sentence for s, _ in KANJI_KUN_SENTENCES.get(char, []))
        or any(s == sentence for s, _ in BARE_KUN_SENTENCES.get(char, []))
    )
    if not curated and not is_standalone_kanji_highlight(char, sentence):
        return False
    if len(distinct_readings(meta)) <= 1:
        return True
    if char in NUMBER_CONTEXT:
        return any(s == sentence for s, _ in NUMBER_CONTEXT[char])
    if char in KANJI_KUN_SENTENCES:
        if any(s == sentence for s, _ in KANJI_KUN_SENTENCES[char]):
            return True
    if char in BARE_KUN_SENTENCES:
        if any(s == sentence for s, _ in BARE_KUN_SENTENCES[char]):
            return True
    if re.search(rf"\*\*{re.escape(char)}\*\*[ぁ-ん]", sentence):
        return True
    return False


def bare_kun_contexts(char: str, meta: dict) -> list[tuple[str, str]]:
    if char in KANJI_KUN_SENTENCES or char not in BARE_KUN_SENTENCES:
        return []
    return list(BARE_KUN_SENTENCES[char])


def build_kanji_contexts(char: str, meta: dict, jukugo_pairs: list[tuple[str, str]], lookup: dict[str, dict]) -> list[dict]:
    contexts: list[tuple[str, str]] = []
    seen_pairs: set[tuple[str, str]] = set()

    def add(sentence: str, reading: str) -> None:
        if not reading or not is_disambiguated_example(char, sentence, meta):
            return
        key = (sentence, reading)
        if key not in seen_pairs:
            seen_pairs.add(key)
            contexts.append(key)

    for sentence, reading in NUMBER_CONTEXT.get(char, []):
        add(sentence, reading)

    for sentence, reading in KANJI_KUN_SENTENCES.get(char, []):
        add(sentence, reading)

    kun_list = meta.get("readings_kun") or []
    on_list = meta.get("readings_on") or []

    for kun_raw in kun_list[:3]:
        ctx = kun_context(char, kun_raw)
        if ctx:
            add(ctx[0], ctx[1])

    for word, yomi in jukugo_pairs:
        if char not in word:
            continue
        idx = word.index(char)
        parts = word_char_readings(word, yomi, lookup)
        if not parts:
            continue
        part = parts[idx]
        j_sentence = sentence_for_jukugo(word)
        if not j_sentence:
            continue
        highlighted = highlight_char_in_word(j_sentence, word, idx)
        if highlighted:
            add(highlighted, part)

    for sentence, reading in bare_kun_contexts(char, meta):
        add(sentence, reading)

    return [{"sentence": s, "reading": r} for s, r in contexts[:4]]


def jukugo_examples(word: str, reading: str) -> list[dict]:
    if word in SKIP_JUKUGO:
        return []
    sentence = sentence_for_jukugo(word)
    if not sentence or not is_natural_example(word, sentence):
        return []
    return [{"sentence": sentence, "reading": reading}]


def katakana_to_hiragana(text: str) -> str:
    chars: list[str] = []
    for ch in text:
        code = ord(ch)
        if 0x30A1 <= code <= 0x30F6:
            chars.append(chr(code - 0x60))
        else:
            chars.append(ch)
    return "".join(chars)


def load_kanji() -> list[dict]:
    lookup = load_kanji_lookup()
    jukugo_pairs = [pair for pairs in JUKUGO_BY_GRADE.values() for pair in pairs]
    rows: list[dict] = []
    seen: set[str] = set()
    for char, meta in lookup.items():
        if not isinstance(meta.get("grade"), int):
            continue
        grade = meta["grade"]
        if grade > 6:
            continue
        if "readings" in meta:
            continue
        examples = build_kanji_contexts(char, meta, jukugo_pairs, lookup)
        if not examples:
            continue
        rows.append(
            {
                "char": char,
                "readings": [examples[0]["reading"]],
                "grade": grade,
                "examples": examples,
                "sentences": [ex["sentence"] for ex in examples],
            }
        )
        seen.add(char)
    for char, meta in SUPPLEMENTAL_KANJI.items():
        if char in seen:
            continue
        examples = [
            {"sentence": s.replace("**{word}**", f"**{char}**"), "reading": meta["readings"][0]}
            for s in meta["sentences"]
        ]
        rows.append(
            {
                "char": char,
                "readings": meta["readings"],
                "grade": meta["grade"],
                "examples": examples,
                "sentences": [ex["sentence"] for ex in examples],
            }
        )
    rows.sort(key=lambda r: (r["grade"], r["char"]))
    return rows


def load_jukugo() -> list[dict]:
    rows: list[dict] = []
    seen: set[str] = set()
    for grade, pairs in JUKUGO_BY_GRADE.items():
        for word, reading in pairs:
            if word in seen or word in SKIP_JUKUGO:
                continue
            seen.add(word)
            examples = jukugo_examples(word, reading)
            if not examples:
                continue
            rows.append(
                {
                    "word": word,
                    "reading": reading,
                    "grade": grade,
                    "examples": examples,
                    "sentences": [ex["sentence"] for ex in examples],
                }
            )
    rows.sort(key=lambda r: (r["grade"], r["word"]))
    return rows


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    kanji = load_kanji()
    jukugo = load_jukugo()
    (OUT / "kanji.json").write_text(json.dumps(kanji, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT / "jukugo.json").write_text(json.dumps(jukugo, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"kanji: {len(kanji)} entries")
    print(f"jukugo: {len(jukugo)} entries")


if __name__ == "__main__":
    main()
