def katakana_to_hiragana(text: str) -> str:
    chars: list[str] = []
    for ch in text:
        code = ord(ch)
        if 0x30A1 <= code <= 0x30F6:
            chars.append(chr(code - 0x60))
        else:
            chars.append(ch)
    return "".join(chars)


def primary_reading(kun: list[str], on: list[str]) -> str:
    for raw in kun + on:
        if not raw:
            continue
        base = re.sub(r"[-.].*$", "", raw)
        base = katakana_to_hiragana(unicodedata.normalize("NFKC", base))
        if base and all("\u3040" <= c <= "\u309f" or c == "ー" for c in base):
            return base.replace("ー", "")
    return ""


def load_kanji() -> list[dict]:
    raw = json.loads(urllib.request.urlopen(KYOIKU_URL, timeout=60).read().decode("utf-8"))
    rows: list[dict] = []
    seen: set[str] = set()
    for char, meta in raw.items():
        grade = meta.get("grade")
        if not grade or grade > 6:
            continue
        reading = primary_reading(meta.get("readings_kun") or [], meta.get("readings_on") or [])
        if not reading:
            continue
        rows.append(
            {
                "char": char,
                "readings": [reading],
                "grade": grade,
                "sentences": [s.format(word=char) for s in KANJI_SENTENCES],
            }
        )
        seen.add(char)
    for char, meta in SUPPLEMENTAL_KANJI.items():
        if char in seen:
            continue
        rows.append(
            {
                "char": char,
                "readings": meta["readings"],
                "grade": meta["grade"],
                "sentences": [s.replace("**{word}**", f"**{char}**").format(word=char) for s in meta["sentences"]],
            }
        )
    rows.sort(key=lambda r: (r["grade"], r["char"]))
    return rows


def load_jukugo() -> list[dict]:
    rows: list[dict] = []
    seen: set[str] = set()
    for grade, pairs in JUKUGO_BY_GRADE.items():
        for word, reading in pairs:
            if word in seen:
                continue
            seen.add(word)
            rows.append(
                {
                    "word": word,
                    "reading": reading,
                    "grade": grade,
                    "sentences": [s.format(word=word) for s in JUKUGO_SENTENCES],
                }
            )
    rows.sort(key=lambda r: (r["grade"], r["word"]))
    return rows


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    kanji = load_kanji()
    jukugo = load_jukugo()
    (OUT / "kanji.json").write_text(json.dumps(kanji, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT / "jukugo.json").write_text(json.dumps(jukugo, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"kanji: {len(kanji)} entries")
    print(f"jukugo: {len(jukugo)} entries")


if __name__ == "__main__":
    main()
