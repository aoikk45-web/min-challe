def readings_for_char(char: str, lookup: dict[str, dict]) -> list[str]:
    meta = lookup.get(char)
    if not meta:
        return []
    if "readings" in meta:
        return list(meta["readings"])
    kun = clean_readings(meta.get("readings_kun") or [])
    on = clean_readings(meta.get("readings_on") or [])
    return kun + on


def split_word_readings(word: str, yomi: str, lookup: dict[str, dict]) -> list[str] | None:
    options = [readings_for_char(ch, lookup) for ch in word]
    if not all(options):
        return None

    def search(i: int, pos: int) -> list[str] | None:
        if i == len(word):
            return [] if pos == len(yomi) else None
        for reading in options[i]:
            if yomi.startswith(reading, pos):
                rest = search(i + 1, pos + len(reading))
                if rest is not None:
                    return [reading] + rest
        return None

    return search(0, 0)


def word_char_readings(word: str, yomi: str, lookup: dict[str, dict]) -> list[str] | None:
    if word in JUKUGO_READING_SPLITS:
        parts = JUKUGO_READING_SPLITS[word]
        if len(parts) == len(word) and "".join(parts) == yomi:
            return parts
    parts = split_word_readings(word, yomi, lookup)
    if parts:
        return parts
    if len(word) == 2:
        mora = [split_yomi(word, yomi, i) for i in range(2)]
        if all(mora) and mora[0] + mora[1] == yomi:
            return mora
    return None


